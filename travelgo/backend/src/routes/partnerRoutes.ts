import { Router } from 'express';
import { PartnerController } from '../controllers/partnerController.js';
import { PartnerResourceController } from '../controllers/partnerResourceController.js';
import { authenticate, requireRoles } from '../middlewares/authMiddleware.js';

const router = Router();
router.use(authenticate, requireRoles('PARTNER'));
router.get('/dashboard', PartnerController.dashboard);
router.get('/businesses', PartnerController.businesses);
router.get('/businesses/:businessId/bookings', PartnerController.bookings);
router.get('/businesses/:id', PartnerController.business);
router.get('/places', PartnerResourceController.listPlaces);
router.post('/places', PartnerResourceController.createPlace);
router.get('/places/:id', PartnerResourceController.getPlace);
router.patch('/places/:id', PartnerResourceController.updatePlace);
router.delete('/places/:id', PartnerResourceController.archivePlace);
router.post('/places/:id/submit', PartnerResourceController.submitPlace);
router.get('/tours', PartnerResourceController.listTours);
router.post('/tours', PartnerResourceController.createTour);
router.get('/tours/:id', PartnerResourceController.getTour);
router.patch('/tours/:id', PartnerResourceController.updateTour);
router.delete('/tours/:id', PartnerResourceController.archiveTour);
router.post('/tours/:id/submit', PartnerResourceController.submitTour);
router.get('/tickets', PartnerResourceController.listTickets);
router.post('/tickets', PartnerResourceController.createTicket);
router.get('/tickets/:id', PartnerResourceController.getTicket);
router.patch('/tickets/:id', PartnerResourceController.updateTicket);
router.delete('/tickets/:id', PartnerResourceController.archiveTicket);
router.get('/blogs', PartnerResourceController.listBlogs);
router.post('/blogs', PartnerResourceController.createBlog);
router.get('/blogs/:id', PartnerResourceController.getBlog);
router.patch('/blogs/:id', PartnerResourceController.updateBlog);
router.delete('/blogs/:id', PartnerResourceController.archiveBlog);
router.post('/blogs/:id/submit', PartnerResourceController.submitBlog);
router.get('/bookings', PartnerResourceController.listBookings);
router.get('/bookings/:id', PartnerResourceController.getBooking);
router.patch('/bookings/:id/status', PartnerResourceController.updateBooking);
export default router;
